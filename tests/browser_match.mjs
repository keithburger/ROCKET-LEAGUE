import { createRequire } from 'module'; const { chromium } = createRequire('/opt/node-tools/node_modules/')('playwright');
import fs from 'fs';
const url = 'http://localhost:8123/index.html', out = '/tmp/claude-0/shots'; fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + e.stack));
await page.goto(url); await page.waitForFunction(() => window.__game, null, { timeout: 60000 });
await page.click('[data-start=versus]');
await page.waitForTimeout(1200); await page.screenshot({ path: out + '/10_countdown.png' });
await page.waitForTimeout(3500);
await page.keyboard.down('KeyW'); await page.keyboard.down('ShiftLeft'); await page.waitForTimeout(2500);
await page.screenshot({ path: out + '/11_playing.png' });
const info = () => page.evaluate(() => { const g = window.__game, m = g.match; return { state: m.state, score: m.scores.slice(), t: +m.timeLeft.toFixed(1), human: m.human.currT.toArray().map(x => +x.toFixed(1)), bot: m.cars[1].currT.toArray().map(x => +x.toFixed(1)), ball: m.ball.pos.toArray().map(x => +x.toFixed(1)), paused: m.paused }; });
console.log('playing', JSON.stringify(await info()));
await page.keyboard.up('KeyW'); await page.keyboard.up('ShiftLeft');
await page.keyboard.press('Escape'); await page.waitForTimeout(500);
console.log('after esc paused?', (await info()).paused); await page.screenshot({ path: out + '/12_pause.png' });
await page.click('#btn-pause-settings'); await page.waitForTimeout(300); await page.screenshot({ path: out + '/13_settings.png' });
await page.click('[data-tab=t-keys]'); await page.waitForTimeout(200); await page.screenshot({ path: out + '/13b_keys.png' });
await page.click('#btn-settings-close'); await page.click('#btn-resume'); await page.waitForTimeout(300);
console.log('after resume paused?', (await info()).paused);
// force a goal for blue
await page.evaluate(() => { const m = window.__game.match; m.ball.reset(0, 2, 49, 0, 0, 40); });
await page.waitForTimeout(1800); await page.screenshot({ path: out + '/14_goal.png' });
console.log('goal', JSON.stringify(await info()));
await page.waitForTimeout(3500); await page.screenshot({ path: out + '/15_replay.png' });
console.log('replay', JSON.stringify(await info()));
await page.keyboard.press('Enter'); await page.waitForTimeout(600);
console.log('after skip', JSON.stringify(await info()));
// end of match: tied goes to overtime
await page.evaluate(() => { const m = window.__game.match; m.timeLeft = 0.05; m.scores = [1, 1]; });
await page.waitForTimeout(5200); console.log('overtime?', await page.evaluate(() => window.__game.match.overtime), JSON.stringify(await info()));
await page.screenshot({ path: out + '/16_overtime.png' });
await page.evaluate(() => { const m = window.__game.match; m.ball.reset(0, 2, -49, 0, 0, -40); });
await page.waitForTimeout(8000);
console.log('ended', JSON.stringify(await info()));
await page.waitForTimeout(2500); await page.screenshot({ path: out + '/17_results.png' });
console.log('errors:', errors.length ? errors.slice(0, 5) : 'none');
await browser.close();
